-- Korak 2: tablica namirnica (vrijednosti na 100 g, iz db/podaci/namirnice.csv)

CREATE TABLE namirnica (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kljuc           text NOT NULL UNIQUE,
    kalorije        NUMERIC(7,2) NOT NULL CHECK (kalorije >= 0),
    proteini        NUMERIC(7,2) NOT NULL CHECK (proteini >= 0),
    ugljikohidrati  NUMERIC(7,2) NOT NULL CHECK (ugljikohidrati >= 0),
    masti           NUMERIC(7,2) NOT NULL CHECK (masti >= 0),
    grama_po_komadu NUMERIC(7,2) NULL,
    napomena        text NULL
);

COMMENT ON TABLE namirnica IS 'Nutritivne vrijednosti namirnica na 100 g (okvirne, USDA/EU tablice)';
COMMENT ON COLUMN namirnica.kalorije IS 'kcal na 100 g, okvirno (USDA/EU tablice)';
COMMENT ON COLUMN namirnica.proteini IS 'g na 100 g, okvirno (USDA/EU tablice)';
COMMENT ON COLUMN namirnica.ugljikohidrati IS 'g na 100 g, okvirno (USDA/EU tablice)';
COMMENT ON COLUMN namirnica.masti IS 'g na 100 g, okvirno (USDA/EU tablice)';
COMMENT ON COLUMN namirnica.grama_po_komadu IS 'masa jednog komada za artikle "(kom)"';

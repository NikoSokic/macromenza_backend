-- Korak 4 (1/3): tablice meni i meni_stavka (iz db/podaci/meniji.csv i meni_stavke.csv)

CREATE TABLE meni (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sifra          text NOT NULL UNIQUE,
    tip_obroka     text NOT NULL CHECK (tip_obroka IN ('RUCAK', 'VECERA')),
    vegetarijanski boolean NOT NULL,
    redni_broj     integer NULL
);

CREATE TABLE meni_stavka (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meni    bigint NOT NULL REFERENCES meni (id) ON DELETE CASCADE,
    id_jelo    bigint NOT NULL REFERENCES jelo (id),
    redoslijed integer NOT NULL,
    oznaka     text NOT NULL,
    kolicina   NUMERIC(4,1) NOT NULL DEFAULT 1 CHECK (kolicina > 0),
    priblizno  boolean NOT NULL DEFAULT false,
    UNIQUE (id_meni, redoslijed)
);

CREATE INDEX meni_stavka_id_meni_idx ON meni_stavka (id_meni);

COMMENT ON TABLE meni IS 'Fiksni meniji menze (ručak/večera, obični/vegetarijanski)';
COMMENT ON COLUMN meni.sifra IS 'meni_id iz meniji.csv (R1, V3, vR8...)';
COMMENT ON TABLE meni_stavka IS 'Jela u meniju; nutritivne vrijednosti računa view v_meni_stavka_nutritivno';
COMMENT ON COLUMN meni_stavka.oznaka IS 'Naziv stavke kako piše na jelovniku (može se razlikovati od jelo.naziv)';
COMMENT ON COLUMN meni_stavka.kolicina IS 'Broj porcija jela u meniju (npr. 3 šnite kruha)';
COMMENT ON COLUMN meni_stavka.priblizno IS 'true = jelo s menija nema vlastitu recepturu, uzeto je slično jelo (ulazi u total)';

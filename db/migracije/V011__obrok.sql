-- Korak 5 (1/2): tablica obrok, konzumacija.id_obrok i decimalna kolicina (porcije po 0,5).
-- Postojeći podaci se ne mijenjaju; povezivanje konzumacija s obrocima je u V012.

CREATE TABLE konzumacija_backup_k5 AS SELECT * FROM konzumacija;

CREATE TABLE obrok (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_korisnik bigint NOT NULL REFERENCES korisnik (id) ON DELETE CASCADE,
    datum       date NOT NULL,
    vrijeme     time NOT NULL,
    tip_obroka  text NOT NULL CHECK (tip_obroka IN ('DORUCAK', 'RUCAK', 'UZINA', 'VECERA')),
    izvor       text NOT NULL DEFAULT 'RUCNO' CHECK (izvor IN ('RUCNO', 'MENI', 'SLIKA', 'OPIS')),
    kreirano    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX obrok_id_korisnik_datum_idx ON obrok (id_korisnik, datum);

ALTER TABLE konzumacija
    ADD COLUMN id_obrok bigint NULL REFERENCES obrok (id) ON DELETE CASCADE;

CREATE INDEX konzumacija_id_obrok_idx ON konzumacija (id_obrok);

ALTER TABLE konzumacija
    ALTER COLUMN kolicina TYPE NUMERIC(4,1) USING kolicina::numeric;

ALTER TABLE konzumacija
    ADD CONSTRAINT konzumacija_kolicina_check CHECK (kolicina > 0 AND kolicina * 2 = trunc(kolicina * 2));

COMMENT ON TABLE konzumacija_backup_k5 IS 'Kopija konzumacija prije koraka 5 (V011)';
COMMENT ON TABLE obrok IS 'Obrok kao cjelina: datum, vrijeme, tip i izvor; jela obroka su u konzumacija';
COMMENT ON COLUMN obrok.izvor IS 'RUCNO, MENI, SLIKA ili OPIS';
COMMENT ON COLUMN konzumacija.id_obrok IS 'Obrok kojem stavka pripada; konzumacija.datum i tip_obroka preuzimaju se iz obroka';
COMMENT ON COLUMN konzumacija.kolicina IS 'Broj porcija, koraci od 0,5';

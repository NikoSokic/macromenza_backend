-- Korak 3 (1/4): jelo postaje decimalno + novi stupci, nova tablica jelo_sastojak.
-- Backup tablice: jelo_backup_k3, konzumacija_backup_k3 (ne brišu se).

CREATE TABLE jelo_backup_k3 AS SELECT * FROM jelo;
CREATE TABLE konzumacija_backup_k3 AS SELECT * FROM konzumacija;

ALTER TABLE jelo
    ALTER COLUMN kalorije       TYPE NUMERIC(8,2) USING kalorije::numeric,
    ALTER COLUMN proteini       TYPE NUMERIC(8,2) USING proteini::numeric,
    ALTER COLUMN ugljikohidrati TYPE NUMERIC(8,2) USING ugljikohidrati::numeric,
    ALTER COLUMN masti          TYPE NUMERIC(8,2) USING masti::numeric;

ALTER TABLE jelo
    ADD COLUMN sifra      integer UNIQUE NULL,
    ADD COLUMN kategorija text NULL,
    ADD COLUMN cijena_eur NUMERIC(5,2) NULL,
    ADD COLUMN napomena   text NULL,
    ADD COLUMN aktivno    boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN jelo.sifra IS 'id jela iz jela.csv (NN 120/2013); NULL za stara ručno unesena jela';
COMMENT ON COLUMN jelo.aktivno IS 'false = jelo se ne nudi u listi/pretrazi, ali stare konzumacije i GET po id-u rade';
COMMENT ON COLUMN jelo.kalorije IS 'Samo za jela bez sastojaka (stara jela); inače vrijedi v_jelo_nutritivno';

CREATE TABLE jelo_sastojak (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jelo           bigint NOT NULL REFERENCES jelo (id) ON DELETE CASCADE,
    id_namirnica      bigint NOT NULL REFERENCES namirnica (id),
    naziv_u_recepturi text NOT NULL,
    grami             NUMERIC(7,2) NOT NULL CHECK (grami > 0)
);

CREATE INDEX jelo_sastojak_id_jelo_idx ON jelo_sastojak (id_jelo);

COMMENT ON TABLE jelo_sastojak IS 'Receptura jela: sastojak i gramaža (neto, već u gramima; kod "ili" alternativa prva opcija)';
COMMENT ON COLUMN jelo_sastojak.naziv_u_recepturi IS 'Naziv sastojka kako piše u NN 120/2013';
COMMENT ON COLUMN jelo_sastojak.grami IS 'Gramaža sastojka u jednoj porciji jela';
